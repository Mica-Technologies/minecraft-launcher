# Builds the macOS / Linux native starter (starter_unix.c) and puts it in front of the jpackage
# launcher, as deploy/windows/starter/build-starter.ps1 does on Windows.
#
# Run by the mac-packaging and linux-packaging profiles between the jpackage app-image step and
# the installer steps. In the image it renames the launcher "<name>" to "<name> Core" (and its
# "<name>.cfg" to match: the jpackage launcher finds its config by its own file name), then installs
# the starter as "<name>", which the Dock, Finder, the .desktop entry and every relaunch run.
# On macOS the bundle is then signed again (ad hoc), since replacing an executable breaks the
# signature jpackage gave it.
#
# usage: build-starter.sh <app image> <name> <environment> <lang dir> <work dir> <java>
#   <app image>  macOS: the .app bundle; Linux: the image folder (holding bin/ and lib/)

set -euo pipefail

app_image="$1"
name="$2"
environment="$3"
lang_dir="$4"
work_dir="$5"
java="$6"
source_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

mkdir -p "$work_dir"

# ---- headers -------------------------------------------------------------------------------
"$java" "$source_dir/../../starter/GenerateStarterStrings.java" "$lang_dir" "$work_dir/starter_strings.h"

if [ "$environment" = "DEV" ]; then data_folder=".MicaMinecraftLauncherDEV"; else data_folder=".MicaMinecraftLauncher"; fi
cat > "$work_dir/starter_build.h" <<EOF
/* Generated by build-starter.sh. Do not edit. */
#pragma once
#define MMCL_APP_NAME "$name"
#define MMCL_DATA_FOLDER "$data_folder"
#define MMCL_DOWNLOAD_URL "https://github.com/Mica-Technologies/minecraft-launcher/releases/latest"
EOF

# ---- compile -------------------------------------------------------------------------------
cflags=(-std=c11 -O2 -Wall -Wextra -Werror -I "$work_dir")
case "$(uname -s)" in
    Darwin)
        cc "${cflags[@]}" -mmacosx-version-min=11.0 "$source_dir/starter_unix.c" -o "$work_dir/starter" \
            -framework CoreFoundation
        launcher_dir="$app_image/Contents/MacOS"
        cfg_dir="$app_image/Contents/app"
        ;;
    Linux)
        # Paths are bounded by PATH_MAX and truncated on purpose if longer; GCC warns regardless.
        cc "${cflags[@]}" -Wno-format-truncation -D_FORTIFY_SOURCE=2 -fstack-protector-strong -fPIE -pie "$source_dir/starter_unix.c" \
            -o "$work_dir/starter" -ldl -lpthread
        launcher_dir="$app_image/bin"
        cfg_dir="$app_image/lib/app"
        ;;
    *)
        echo "build-starter.sh: unsupported OS $(uname -s)" >&2
        exit 1
        ;;
esac

# ---- stage into the app image --------------------------------------------------------------
if [ ! -e "$launcher_dir/$name Core" ]; then
    if [ ! -e "$launcher_dir/$name" ]; then
        echo "build-starter.sh: the app image has no '$launcher_dir/$name' to put the starter in front of" >&2
        exit 1
    fi
    mv "$launcher_dir/$name" "$launcher_dir/$name Core"
    mv "$cfg_dir/$name.cfg" "$cfg_dir/$name Core.cfg"
fi
cp "$work_dir/starter" "$launcher_dir/$name"
chmod 755 "$launcher_dir/$name"

if [ "$(uname -s)" = "Darwin" ]; then
    codesign --force --deep --sign - "$app_image"
    codesign --verify --deep --strict "$app_image"
fi
echo "Starter installed: $launcher_dir/$name -> $launcher_dir/$name Core"
