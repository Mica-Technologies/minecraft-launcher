import java.io.IOException;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Properties;
import java.util.stream.Stream;

/**
 * Generates {@code starter_strings.h} for the native starters (Windows, macOS, Linux) from the
 * launcher's resource bundles, so a launcher that cannot start still explains itself in the
 * user's language.
 *
 * <p>Run as a single-file program with the build's JDK:
 * {@code java GenerateStarterStrings.java <lang dir> <output header>}.
 *
 * <p>Each string is emitted as {@code T("...")} with every non-ASCII character as a C universal
 * character name. The including file defines {@code T} and {@code STARTER_CHAR}: wide strings on
 * Windows ({@code L##s}, {@code wchar_t}), UTF-8 elsewhere ({@code s}, {@code char}). A key a
 * locale lacks is {@code NULL}, and the starter falls back to English. The order of {@link #KEYS}
 * defines the {@code S_*} enum the starters use.
 */
public class GenerateStarterStrings
{
    static final List< String > KEYS = List.of(
            "starter.failed.heading",
            "starter.failed.body",
            "starter.missing.body",
            "starter.crashed.heading",
            "starter.crashed.body",
            "starter.button.repair",
            "starter.button.repair.note",
            "starter.button.logs",
            "starter.details.show",
            "starter.details.hide",
            "starter.details.exitCode",
            "starter.details.output",
            "starter.repair.heading",
            "starter.repair.failed",
            "starter.repair.notFound",
            "starter.reinstall.failed.body",
            "starter.reinstall.missing.body",
            "starter.crashed.body.noCode",
            "starter.button.download",
            "starter.button.download.note",
            "starter.button.close" );

    public static void main( String[] args ) throws IOException
    {
        if ( args.length != 2 ) {
            System.err.println( "usage: java GenerateStarterStrings.java <lang dir> <output header>" );
            System.exit( 2 );
        }
        Path langDir = Path.of( args[ 0 ] );
        Path root = langDir.resolve( "DisplayStrings.properties" );
        List< String[] > bundles = new ArrayList<>();   // { tag, file }
        bundles.add( new String[] { "en", root.toString() } );
        try ( Stream< Path > files = Files.list( langDir ) ) {
            files.map( Path::getFileName ).map( Path::toString )
                 .filter( n -> n.startsWith( "DisplayStrings_" ) && n.endsWith( ".properties" ) ).sorted()
                 .forEach( n -> bundles.add( new String[] {
                         n.substring( "DisplayStrings_".length(), n.length() - ".properties".length() ).replace( '_', '-' ),
                         langDir.resolve( n ).toString() } ) );
        }
        Properties english = load( root );
        for ( String key : KEYS ) {
            if ( english.getProperty( key ) == null ) {
                throw new IllegalStateException( "DisplayStrings.properties has no '" + key + "'" );
            }
        }

        StringBuilder h = new StringBuilder();
        h.append( "/* Generated by GenerateStarterStrings.java from src/main/resources/lang. Do not edit. */\n" );
        h.append( "#pragma once\n" );
        h.append( "enum StarterString {\n" );
        for ( String key : KEYS ) {
            h.append( "    " ).append( enumName( key ) ).append( ",\n" );
        }
        h.append( "    S_COUNT\n};\n" );
        h.append( "typedef struct { const char *tag; const STARTER_CHAR *s[ S_COUNT ]; } StarterLocale;\n" );
        h.append( "#define STARTER_LOCALE_COUNT " ).append( bundles.size() ).append( "\n" );
        h.append( "static const StarterLocale STARTER_LOCALES[] = {\n" );
        for ( String[] bundle : bundles ) {
            Properties values = load( Path.of( bundle[ 1 ] ) );
            h.append( "    { \"" ).append( bundle[ 0 ] ).append( "\", {\n" );
            for ( int i = 0; i < KEYS.size(); i++ ) {
                String value = values.getProperty( KEYS.get( i ) );
                h.append( "        " ).append( value == null ? "NULL" : literal( value ) )
                 .append( i + 1 < KEYS.size() ? ",\n" : "\n" );
            }
            h.append( "    } },\n" );
        }
        h.append( "};\n" );
        Path out = Path.of( args[ 1 ] );
        if ( out.getParent() != null ) {
            Files.createDirectories( out.getParent() );
        }
        Files.writeString( out, h.toString(), StandardCharsets.UTF_8 );
    }

    static Properties load( Path file ) throws IOException
    {
        Properties p = new Properties();
        try ( Reader r = Files.newBufferedReader( file, StandardCharsets.UTF_8 ) ) {
            p.load( r );
        }
        return p;
    }

    /** {@code starter.details.exitCode} becomes {@code S_DETAILS_EXIT_CODE}. */
    static String enumName( String key )
    {
        StringBuilder sb = new StringBuilder( "S" );
        for ( String part : key.substring( "starter.".length() ).split( "\\." ) ) {
            sb.append( '_' ).append( part.replaceAll( "([a-z])([A-Z])", "$1_$2" ).toUpperCase( java.util.Locale.ROOT ) );
        }
        return sb.toString();
    }

    /** A string as {@code T("...")}, ASCII as is and everything else as universal character names. */
    static String literal( String s )
    {
        StringBuilder sb = new StringBuilder( "T(\"" );
        s.codePoints().forEach( c -> {
            if ( c == '\\' ) {
                sb.append( "\\\\" );
            }
            else if ( c == '"' ) {
                sb.append( "\\\"" );
            }
            else if ( c == '\n' ) {
                sb.append( "\\n" );
            }
            else if ( c == '\t' ) {
                sb.append( "\\t" );
            }
            else if ( c >= 0x20 && c <= 0x7E ) {
                sb.append( ( char ) c );
            }
            else if ( c > 0xFFFF ) {
                sb.append( String.format( "\\U%08X", c ) );
            }
            else if ( c >= 0xA0 ) {
                sb.append( String.format( "\\u%04X", c ) );
            }
        } );
        return sb.append( "\")" ).toString();
    }
}
