//! Embeds the localization bundles at build time.
//!
//! Two folders are read:
//!
//! * `src/main/resources/lang/` at the repository root: the Java launcher's bundles, the single
//!   source of truth shared by both launchers (never copied or forked);
//! * `rust/i18n/`: the Rust-only overlay, whose keys win over the Java ones.
//!
//! Every `DisplayStrings[_suffix].properties` file found is embedded with `include_bytes!`, and the
//! generated `bundles.rs` lists them by suffix (`""` for the root/English bundle, `"pt_BR"`, ...).

use std::collections::BTreeSet;
use std::env;
use std::fs;
use std::path::{Path, PathBuf};

const BASE: &str = "DisplayStrings";

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    // crates/mmcl-i18n -> rust -> repository root
    let rust_root = manifest
        .parent()
        .and_then(Path::parent)
        .expect("mmcl-i18n must live at rust/crates/mmcl-i18n")
        .to_path_buf();
    let repo_root = rust_root
        .parent()
        .expect("rust/ must have a parent")
        .to_path_buf();
    let java_dir = repo_root
        .join("src")
        .join("main")
        .join("resources")
        .join("lang");
    let overlay_dir = rust_root.join("i18n");

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed={}", java_dir.display());
    println!("cargo:rerun-if-changed={}", overlay_dir.display());

    let java = scan(&java_dir);
    let overlay = scan(&overlay_dir);
    if !java.iter().any(|(suffix, _)| suffix.is_empty()) {
        panic!(
            "mmcl-i18n: the Java root bundle {}/{}.properties was not found; the Rust build reads \
             the Java launcher's bundles directly",
            java_dir.display(),
            BASE
        );
    }

    let mut suffixes = BTreeSet::new();
    for (suffix, _) in java.iter().chain(overlay.iter()) {
        suffixes.insert(suffix.clone());
    }

    let mut out = String::new();
    out.push_str("// @generated by mmcl-i18n/build.rs. Do not edit.\n\n");
    out.push_str("/// Java bundles: (suffix, raw file bytes).\n");
    out.push_str("pub(crate) static JAVA_FILES: &[(&str, &[u8])] = &[\n");
    for (suffix, path) in &java {
        println!("cargo:rerun-if-changed={}", path.display());
        out.push_str(&format!(
            "    ({:?}, include_bytes!({:?})),\n",
            suffix,
            path.display().to_string()
        ));
    }
    out.push_str("];\n\n");
    out.push_str("/// Rust overlay bundles: (suffix, raw file bytes).\n");
    out.push_str("pub(crate) static OVERLAY_FILES: &[(&str, &[u8])] = &[\n");
    for (suffix, path) in &overlay {
        println!("cargo:rerun-if-changed={}", path.display());
        out.push_str(&format!(
            "    ({:?}, include_bytes!({:?})),\n",
            suffix,
            path.display().to_string()
        ));
    }
    out.push_str("];\n\n");
    out.push_str("/// Every suffix that has a Java file, an overlay file, or both (sorted).\n");
    out.push_str("pub(crate) static SUFFIXES: &[&str] = &[\n");
    for suffix in &suffixes {
        out.push_str(&format!("    {suffix:?},\n"));
    }
    out.push_str("];\n\n");
    out.push_str(&format!(
        "pub(crate) const SUFFIX_COUNT: usize = {};\n",
        suffixes.len()
    ));

    let dest = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR")).join("bundles.rs");
    fs::write(&dest, out).expect("write bundles.rs");
}

/// Lists `DisplayStrings*.properties` in `dir` as (suffix, path), sorted by suffix.
fn scan(dir: &Path) -> Vec<(String, PathBuf)> {
    let mut found = Vec::new();
    let Ok(entries) = fs::read_dir(dir) else {
        return found;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if !path.is_file() {
            continue;
        }
        let Some(name) = path.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        let Some(stem) = name.strip_suffix(".properties") else {
            continue;
        };
        let suffix = if stem == BASE {
            String::new()
        } else if let Some(rest) = stem.strip_prefix(BASE).and_then(|r| r.strip_prefix('_')) {
            if rest.is_empty() {
                continue;
            }
            rest.to_string()
        } else {
            continue;
        };
        let abs = fs::canonicalize(&path).unwrap_or(path);
        found.push((suffix, strip_verbatim(abs)));
    }
    found.sort();
    found
}

/// `fs::canonicalize` on Windows returns `\\?\C:\...`; `include_bytes!` accepts it, but the plain
/// form keeps the generated file readable.
fn strip_verbatim(path: PathBuf) -> PathBuf {
    let s = path.display().to_string();
    match s.strip_prefix(r"\\?\") {
        Some(rest) if !rest.starts_with("UNC") => PathBuf::from(rest),
        _ => path,
    }
}
