//! Generates the token tables from the Java launcher's seven `ui-tokens-*.css` sheets, so a
//! `tools/theme-roles` regeneration flows into Rust with no hand edits. The build fails when the
//! sheets disagree on their token set or a value cannot be read as a colour.

#[allow(dead_code)]
#[path = "src/css.rs"]
mod css;

use std::fmt::Write as _;
use std::path::PathBuf;

/// `(const name, file name)` in `TokenSheet` declaration order.
const SHEETS: [(&str, &str); 7] = [
    ("DARK", "ui-tokens-dark.css"),
    ("LIGHT", "ui-tokens-light.css"),
    ("BLUE_GRAY", "ui-tokens-bluegray.css"),
    ("ORANGE_PURPLE", "ui-tokens-orangepurple.css"),
    ("CREEPER", "ui-tokens-creeper.css"),
    ("NATIVE", "ui-tokens-native.css"),
    ("NATIVE_LIGHT", "ui-tokens-native-light.css"),
];

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let dir = manifest.join("../../../src/main/resources/ui");
    let dir = dir.canonicalize().unwrap_or_else(|e| {
        panic!(
            "mmcl-theme: token sheet folder {} not found ({e}); the crate builds from the launcher repo",
            dir.display()
        )
    });
    println!("cargo:rerun-if-changed=src/css.rs");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut names: Option<Vec<String>> = None;
    let mut tables = Vec::new();
    let mut references = Vec::new();
    for (konst, file) in SHEETS {
        let path = dir.join(file);
        println!("cargo:rerun-if-changed={}", path.display());
        let source = std::fs::read_to_string(&path)
            .unwrap_or_else(|e| panic!("mmcl-theme: cannot read {}: {e}", path.display()));
        let tokens = css::root_tokens(&source)
            .unwrap_or_else(|| panic!("mmcl-theme: {file} has no .root block"));
        let these: Vec<String> = tokens.iter().map(|(k, _)| k.clone()).collect();
        match &names {
            None => names = Some(these.clone()),
            Some(reference) => {
                let mut a = reference.clone();
                let mut b = these.clone();
                a.sort();
                b.sort();
                assert_eq!(
                    a, b,
                    "mmcl-theme: {file} defines a different token set than {}",
                    SHEETS[0].1
                );
            }
        }
        let lookup = |name: &str| {
            tokens
                .iter()
                .find(|(k, _)| k == name)
                .map(|(_, v)| v.clone())
        };
        let mut values = Vec::new();
        for (name, raw) in &tokens {
            let value = if raw.starts_with('-') {
                // One level of lookup, as ThemeTokensTest resolves `-color-popup`.
                let target = lookup(raw).unwrap_or_else(|| {
                    panic!("mmcl-theme: {file}: {name} names unknown token {raw}")
                });
                references.push((file, name.clone(), raw.clone()));
                target
            } else {
                raw.clone()
            };
            let rgba = css::parse_color(&value).unwrap_or_else(|| {
                panic!("mmcl-theme: {file}: {name}: unsupported colour {value:?}")
            });
            values.push((name.clone(), rgba));
        }
        tables.push((konst, file, values));
    }
    let names = names.expect("at least one sheet");

    let mut out = String::new();
    out.push_str(
        "// @generated by mmcl-theme/build.rs from src/main/resources/ui/ui-tokens-*.css\n\n",
    );
    writeln!(out, "/// Number of colour tokens every sheet defines.").unwrap();
    writeln!(out, "pub const TOKEN_COUNT: usize = {};", names.len()).unwrap();
    writeln!(
        out,
        "/// Every token name (`-color-*` then `-md-*`, in the dark sheet's order)."
    )
    .unwrap();
    writeln!(out, "pub const TOKEN_NAMES: [&str; TOKEN_COUNT] = [").unwrap();
    for n in &names {
        writeln!(out, "    {n:?},").unwrap();
    }
    out.push_str("];\n\n");

    out.push_str("/// Every colour token of one token sheet, as a typed field.\n");
    out.push_str("///\n/// Field names are the CSS lookup names without the leading dash and with `-` -> `_`\n");
    out.push_str("/// (`-color-bg-soft` -> `color_bg_soft`). References such as `-color-popup:\n");
    out.push_str("/// -md-surface-container-high` are resolved to the referenced value.\n");
    out.push_str("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\npub struct Tokens {\n");
    for n in &names {
        writeln!(out, "    /// `{n}`").unwrap();
        writeln!(out, "    pub {}: Rgba,", css::field_name(n)).unwrap();
    }
    out.push_str("}\n\n");

    out.push_str("impl Tokens {\n");
    out.push_str("    /// Looks a token up by its CSS name (`-color-bg`, `-md-primary`, ...).\n");
    out.push_str("    pub fn get(&self, name: &str) -> Option<Rgba> {\n        match name {\n");
    for n in &names {
        writeln!(
            out,
            "            {n:?} => Some(self.{}),",
            css::field_name(n)
        )
        .unwrap();
    }
    out.push_str("            _ => None,\n        }\n    }\n\n");
    out.push_str("    /// Every token value, in `TOKEN_NAMES` order.\n");
    out.push_str("    pub fn values(&self) -> [Rgba; TOKEN_COUNT] {\n        [\n");
    for n in &names {
        writeln!(out, "            self.{},", css::field_name(n)).unwrap();
    }
    out.push_str("        ]\n    }\n}\n\n");

    for (konst, file, values) in &tables {
        writeln!(out, "/// Tokens of `{file}`.").unwrap();
        writeln!(out, "pub(crate) const {konst}: Tokens = Tokens {{").unwrap();
        for (name, rgba) in values {
            writeln!(out, "    {}: Rgba(0x{rgba:08X}),", css::field_name(name)).unwrap();
        }
        out.push_str("};\n\n");
    }

    out.push_str(
        "/// `(sheet file, token, referenced token)` for every token defined by reference.\n",
    );
    out.push_str("pub const TOKEN_REFERENCES: &[(&str, &str, &str)] = &[\n");
    for (file, name, target) in &references {
        writeln!(out, "    ({file:?}, {name:?}, {target:?}),").unwrap();
    }
    out.push_str("];\n\n");

    out.push_str("/// Absolute folder of the CSS sheets the tables were generated from (tests re-read it).\n");
    out.push_str("#[cfg(test)]\n");
    writeln!(
        out,
        "pub(crate) const CSS_DIR: &str = {:?};",
        dir.to_string_lossy()
    )
    .unwrap();

    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("tokens.rs");
    std::fs::write(&dest, out).expect("write generated tokens");
}
