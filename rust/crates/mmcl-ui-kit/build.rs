//! Generates the launcher icon set from the Java launcher's `LauncherIcons.java`.
//!
//! `LauncherIcons.java` is itself the output of `tools/launcher-icons/build_icons.py`, so reading
//! it keeps that script the single source: a regenerated icon set flows into Rust with no hand
//! edits. Each `public static final String NAME = "<svg path data>";` becomes an `Icon` variant
//! whose SVG document (`<svg viewBox="0 0 24 24"><path d=".."/></svg>`) is embedded as a string.

use std::fmt::Write as _;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let java = manifest.join(
        "../../../src/main/java/com/micatechnologies/minecraft/launcher/gui/LauncherIcons.java",
    );
    println!("cargo:rerun-if-changed={}", java.display());
    println!("cargo:rerun-if-changed=build.rs");
    let source = std::fs::read_to_string(&java).unwrap_or_else(|e| {
        panic!(
            "mmcl-ui-kit: cannot read {} ({e}); the crate builds from the launcher repo",
            java.display()
        )
    });

    let icons = parse_icons(&source);
    assert!(
        icons.len() >= 30,
        "mmcl-ui-kit: only {} icons parsed from LauncherIcons.java; is the parser broken?",
        icons.len()
    );

    let mut out = String::new();
    out.push_str("// Generated by mmcl-ui-kit/build.rs from LauncherIcons.java. Do not edit.\n\n");
    out.push_str(
        "/// One launcher glyph: SVG path data in a 24x24 box (Material Symbols Rounded filled,\n",
    );
    out.push_str("/// Apache-2.0, plus custom Minecraft glyphs).\n");
    out.push_str(
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, IntoElement)]\npub enum Icon {\n",
    );
    for (name, _) in &icons {
        let _ = writeln!(out, "    /// `LauncherIcons.{name}`\n    {},", camel(name));
    }
    out.push_str("}\n\n");
    let _ = writeln!(
        out,
        "/// Number of icons.\npub const ICON_COUNT: usize = {};\n",
        icons.len()
    );
    out.push_str("impl Icon {\n    /// Every icon, in `LauncherIcons.java` order.\n");
    out.push_str("    pub const ALL: [Icon; ICON_COUNT] = [\n");
    for (name, _) in &icons {
        let _ = writeln!(out, "        Icon::{},", camel(name));
    }
    out.push_str("    ];\n\n");
    out.push_str("    /// The SVG path data (24x24 viewBox).\n    pub const fn path(self) -> &'static str {\n        match self {\n");
    for (name, path) in &icons {
        let _ = writeln!(out, "            Icon::{} => {:?},", camel(name), path);
    }
    out.push_str("        }\n    }\n\n");
    out.push_str("    /// The Java constant name, e.g. `ARROW_UP`.\n    pub const fn java_name(self) -> &'static str {\n        match self {\n");
    for (name, _) in &icons {
        let _ = writeln!(out, "            Icon::{} => {:?},", camel(name), name);
    }
    out.push_str("        }\n    }\n\n");
    out.push_str("    /// The snake-case file stem, e.g. `arrow_up`.\n    pub const fn file_stem(self) -> &'static str {\n        match self {\n");
    for (name, _) in &icons {
        let _ = writeln!(
            out,
            "            Icon::{} => {:?},",
            camel(name),
            name.to_lowercase()
        );
    }
    out.push_str("        }\n    }\n\n");
    out.push_str("    /// The complete SVG document GPUI's `svg()` element renders.\n    pub const fn svg_document(self) -> &'static str {\n        match self {\n");
    for (name, path) in &icons {
        let doc = format!(
            "<svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 24 24\"><path d=\"{path}\"/></svg>"
        );
        let _ = writeln!(out, "            Icon::{} => {:?},", camel(name), doc);
    }
    out.push_str("        }\n    }\n}\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR")).join("icons.rs");
    std::fs::write(&dest, out).expect("write icons.rs");
}

/// `(NAME, path data)` for every `public static final String` in the file.
fn parse_icons(source: &str) -> Vec<(String, String)> {
    let mut icons = Vec::new();
    let marker = "public static final String ";
    let mut rest = source;
    while let Some(at) = rest.find(marker) {
        rest = &rest[at + marker.len()..];
        let Some(eq) = rest.find('=') else { break };
        let name = rest[..eq].trim().to_string();
        let Some(end) = rest.find(';') else { break };
        let body = &rest[eq + 1..end];
        let mut value = String::new();
        let mut in_str = false;
        let mut chars = body.chars();
        while let Some(c) = chars.next() {
            match (in_str, c) {
                (false, '"') => in_str = true,
                (true, '"') => in_str = false,
                (true, '\\') => {
                    if let Some(next) = chars.next() {
                        value.push(next);
                    }
                }
                (true, c) => value.push(c),
                _ => {}
            }
        }
        assert!(
            name.chars()
                .all(|c| c.is_ascii_uppercase() || c.is_ascii_digit() || c == '_'),
            "mmcl-ui-kit: unexpected constant name {name:?} in LauncherIcons.java"
        );
        assert!(
            !value.is_empty() && !value.contains('"') && !value.contains('<'),
            "mmcl-ui-kit: icon {name} has unusable path data"
        );
        icons.push((name, value));
        rest = &rest[end + 1..];
    }
    icons
}

/// `ARROW_UP` -> `ArrowUp`.
fn camel(name: &str) -> String {
    name.split('_')
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut s = String::new();
            let mut cs = p.chars();
            if let Some(f) = cs.next() {
                s.push(f.to_ascii_uppercase());
            }
            s.extend(cs.map(|c| c.to_ascii_lowercase()));
            s
        })
        .collect()
}
